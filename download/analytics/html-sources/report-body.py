def P(text, style=body):
    return Paragraph(text, style)


def add_heading(text, style=h1, level=0):
    key = 'h_' + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1_block(text, first_para):
    """H1 + accent rule + первый абзац, без отрыва заголовка."""
    rule = HRFlowable(width='100%', color=ACCENT, thickness=1.2,
                      spaceBefore=0, spaceAfter=10)
    return [CondPageBreak(H1_THRESHOLD),
            KeepTogether([add_heading(text), rule, first_para])]


def safe_keep(elements):
    total = 0
    for el in elements:
        _, h = el.wrap(AVAIL, PAGE_H)
        total += h
    if total <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    if len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def styled_table(header, rows, ratios, stripe=True):
    widths = [r * AVAIL for r in ratios]
    data = [[P(f'<b>{c}</b>', th) for c in header]]
    for row in rows:
        data.append([c if isinstance(c, (Paragraph, Image)) else P(str(c), td)
                     for c in row])
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]
    if stripe:
        for i in range(1, len(data)):
            style.append(('BACKGROUND', (0, i), (-1, i),
                          TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    assert sum(widths) <= AVAIL + 0.5
    return t


def fit_image(path, max_w, max_h):
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_w / ow, max_h / oh, 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


def figure(path, cap, max_h=295):
    img = fit_image(path, AVAIL, max_h)
    img.hAlign = 'CENTER'
    return [Spacer(1, 14), KeepTogether([img, Spacer(1, 6), P(cap, caption)]),
            Spacer(1, 12)]


