import { DISHES } from './dishes';

/** Ингредиенты-маркеры глютена (строго: пшеница, рожь, ячмень, овёс, паста, хлеб, панировка) */
const GLUTEN_RE =
  /мука|пшеничн|паста|макарон|спагетти|лапш|хлеб|булк|сухар|панировочн|кроутон|тесто|лаваш|пита|кускус|булгур|сейтан|ячнев|перлов|рожь|овсян|печенье|крекер|слоёное тесто|пельмен/i;

/** Ингредиенты-маркеры лактозы (молочка целиком — строгий фильтр) */
const LACTOSE_RE =
  /молок|сливк|йогурт|сметан|сыр|кефир|ряженк|простокваш|творог|маскарпоне|рикотта|брынз|моцарелла|фета|пармезан|чеддер|сулугуни|сливочное масло/i;

/** Сахар/быстрые углеводы для «Низкого ГИ» */
const SUGAR_RE = /сахар|мёд|\bмед\b|глазур|карамел|шоколад|сгущен|сгущён|варенье|джем/i;
/** Быстрые углеводы в ингредиентах (кроме сахара): картофель, белая мука, паста, хлеб, белый рис */
const FAST_CARB_RE = /картоф|паста|макарон|лапш|хлеб|белый рис|мука|тесто/i;

/** Дорогие продукты — исключаем из «Ужина до 300 ₽» */
const EXPENSIVE_RE =
  /говядин|рибай|вырезк|стейк|лосос|сёмг|семг|форель|креветк|тунец|мидии|кальмар|дорадо|баран|ягнят|сыр|колбас|бекон|ветчин|крабов|маскарпоне|фета|индейк|оливк/i;

/** Нельзя в детском меню: острое, алкоголь, экзотика, маринады, кофе */
const KIDS_BAD_RE =
  /чили|вин[оа]|коньяк|ром\b|кофе|алкогол|рокфор|плесенью|креветк|кальмар|мидии|устриц|маринован|бальзамик|виски|джин|текила/i;

/** Печь/много посуды — исключаем из «Минимума посуды» */
const OVEN_RE = /духовк|противень|запеканк|в форму|мультиварк|аэрогриль|рукав|пергамент/i;

export interface Collection {
  id: string;
  titleRu: string;
  descRu: string;
  emoji: string;
  /** id блюд, попавших в подборку (вычисляется один раз при загрузке) */
  ids: ReadonlySet<string>;
}

function build(pred: (d: (typeof DISHES)[number]) => boolean): ReadonlySet<string> {
  return new Set(DISHES.filter(pred).map((d) => d.id));
}

